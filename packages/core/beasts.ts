/**
 * The beasts of myth and nature as the body graph would hold them. A beast
 * is a form, not an assembly: an anatomical specification in words, the shape
 * wanted in numbers (the similarity metric of beasts-measure.ts reads it) and the
 * body itself drawn by hand as a text fixture. Where the tables cannot say a
 * thing, `unexpressible` says so in words.
 */
import type { CoverId } from "./graph.js";

/** The shape of a body in the numbers the similarity reads (beasts-measure.ts `features`). */
export interface Shape {
  torsos: number;
  /** Tips of arms, legs and tentacles that hold no head. */
  limbs: number;
  tails: number;
  heads: number;
  eyes: number;
  hand: number;
  claw: number;
  hoof: number;
  pincer: number;
  sucker: number;
  foot: number;
  mouth: number;
  sting: number;
  wings: number;
  gills: number;
  /** The cover at least half of the segments wear. */
  cover: CoverId;
}

export type ShapeKey = Exclude<keyof Shape, "cover">;

export interface Anatomy {
  torsos: string;
  limbs: string;
  endings: string;
  heads: string;
  cover: string;
  membranes: string;
  breath: string;
  eats: string;
  attack: string;
  moves: string;
}

export interface Beast {
  id: string;
  ru: string;
  anatomy: Anatomy;
  want: Shape;
  fixture: string;
  /** What neither the tables nor the operations can say, in words. */
  unexpressible: string[];
}

