/**
 * Writes docs/api.md: every name the two packages export, grouped by the module
 * it comes from, with the first line of its doc comment. Run after changing an
 * index: `npm run docs:api`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = join(import.meta.dirname, "..");

function modulesOf(index: string): string[] {
  const text = readFileSync(index, "utf8");
  return [...text.matchAll(/export \* from "(\.[^"]+)\.js";/g)].map((m) => join(dirname(index), `${m[1]}.ts`));
}

function exportsOf(file: string): { name: string; kind: string; doc: string }[] {
  const text = readFileSync(file, "utf8");
  const out: { name: string; kind: string; doc: string }[] = [];
  const re = /(?:\/\*\*([\s\S]*?)\*\/\s*)?export (?:declare )?(?:abstract )?(function|const|let|class|interface|type|enum) ([A-Za-z_$][\w$]*)/g;
  for (const m of text.matchAll(re)) {
    const doc = (m[1] ?? "").split("\n").map((l) => l.replace(/^\s*\*\s?/, "").trim()).filter((l) => l !== "")[0] ?? "";
    out.push({ name: m[3]!, kind: m[2]!, doc });
  }
  return out;
}

const lines: string[] = ["# API", "", "Generated by `npm run docs:api` from the package indexes. Version 0.1: the surface is wide and not yet stable.", ""];
for (const [pkg, dir] of [["@mutant-engine/core", "packages/core"], ["@mutant-engine/view", "packages/view"]] as const) {
  lines.push(`## ${pkg}`, "");
  for (const file of modulesOf(join(ROOT, dir, "index.ts"))) {
    const names = exportsOf(file);
    if (names.length === 0) continue;
    lines.push(`### ${file.slice(join(ROOT, dir).length + 1)}`, "");
    for (const e of names) lines.push(`- \`${e.name}\` (${e.kind})${e.doc === "" ? "" : ` — ${e.doc}`}`);
    lines.push("");
  }
}
writeFileSync(join(ROOT, "docs", "api.md"), lines.join("\n"));
console.log(`docs/api.md: ${lines.length} lines`);
